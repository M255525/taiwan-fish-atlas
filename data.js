/* 某區域、海域、月份可捕到的魚 */
FA.catchFor = function(region, zone, month){
  return FA.FISH.filter(function(f){
    return f.at.some(function(a){ return a.z === zone && a.months[month] && a.regions.indexOf(region) >= 0; });
  });
};
/* 某魚在某海域一年中有出現的月份（可限定區域） */
FA.monthsOf = function(f, zone, region){
  var out = {};
  f.at.forEach(function(a){
    if (a.z !== zone || (region && a.regions.indexOf(region) < 0)) return;
    for (var m in a.months) out[m] = 1;
  });
  return out;
};
FA.portsOf = function(f){
  return FA.PORTS.filter(function(p){ return f.at.some(function(a){ return a.regions.indexOf(p.r) >= 0; }); });
};
